import { z } from 'zod'

import { apiDelete, apiGet, apiPost } from './client'

/**
 * Integrations API — GA4 / Shopify / GSC connections live in the backend's
 * `apps.integrations`. The dashboard only needs to know which providers are
 * connected (to flip catalog cards and gate the Analytics tab).
 */

function normalizeEmail(email: string): string {
  return email.toLowerCase().trim()
}

export const integrationStatusSchema = z.object({
  provider: z.string(),
  provider_display: z.string().optional().default(''),
  is_active: z.boolean().optional().default(false),
})
export type IntegrationStatus = z.infer<typeof integrationStatusSchema>

/** GET /api/integrations/status/?email=&org_id= → the org's connected integrations. */
export async function getIntegrationStatus(
  email: string,
  orgId?: number,
): Promise<IntegrationStatus[]> {
  const data = await apiGet<unknown>('/api/integrations/status/', {
    params: { email: normalizeEmail(email), org_id: orgId ? String(orgId) : undefined },
  })
  return z.array(integrationStatusSchema).parse(data)
}

/* ─────────────────────────────────────────────────────── Google Analytics (GA4) */

/** GET /api/integrations/google-analytics/auth-url/?email= → the Google OAuth URL. */
export async function getGAAuthUrl(email: string): Promise<string> {
  const data = await apiGet<unknown>('/api/integrations/google-analytics/auth-url/', {
    params: { email: normalizeEmail(email) },
  })
  return z.object({ auth_url: z.string() }).parse(data).auth_url
}

/** POST /api/integrations/google-analytics/callback/ → exchange the OAuth code. */
export async function sendGACallback(email: string, code: string): Promise<void> {
  await apiPost<unknown>('/api/integrations/google-analytics/callback/', {
    email: normalizeEmail(email),
    code,
  })
}

/** This app's origin — passed so the backend redirects the OAuth callback back here. */
function frontendBase(): string | undefined {
  return typeof window !== 'undefined' ? window.location.origin : undefined
}

/* ─────────────────────────────────────────────────────────────── Webflow (OAuth) */

export const webflowSiteSchema = z.object({
  id: z.string(),
  name: z.string(),
  preview_url: z.string().optional().default(''),
})
export type WebflowSite = z.infer<typeof webflowSiteSchema>

const webflowSitesResponseSchema = z.object({
  sites: z.array(webflowSiteSchema).default([]),
  selected_site_id: z.string().optional().default(''),
})
export type WebflowSites = z.infer<typeof webflowSitesResponseSchema>

/** GET webflow/auth-url/ → the Webflow consent URL to redirect the browser to. */
export async function getWebflowAuthUrl(
  email: string,
  returnTo?: string,
  orgId?: number,
): Promise<string> {
  const data = await apiGet<unknown>('/api/integrations/webflow/auth-url/', {
    params: {
      email: normalizeEmail(email),
      return_to: returnTo,
      org_id: orgId ? String(orgId) : undefined,
      frontend_base: frontendBase(),
    },
  })
  return z.object({ auth_url: z.string() }).parse(data).auth_url
}

/** GET webflow/sites/ → the connected account's sites + which one is selected. */
export async function getWebflowSites(email: string, orgId?: number): Promise<WebflowSites> {
  const data = await apiGet<unknown>('/api/integrations/webflow/sites/', {
    params: { email: normalizeEmail(email), org_id: orgId ? String(orgId) : undefined },
  })
  return webflowSitesResponseSchema.parse(data)
}

/** POST webflow/select-site/ → choose which Webflow site this org edits. */
export async function selectWebflowSite(
  email: string,
  siteId: string,
  orgId?: number,
): Promise<void> {
  await apiPost<unknown>('/api/integrations/webflow/select-site/', {
    email: normalizeEmail(email),
    site_id: siteId,
    org_id: orgId,
  })
}

/** DELETE webflow/disconnect/ → drop the Webflow connection for this org. */
export async function disconnectWebflow(email: string, orgId?: number): Promise<void> {
  await apiDelete<unknown>('/api/integrations/webflow/disconnect/', undefined, {
    params: { email: normalizeEmail(email), org_id: orgId ? String(orgId) : undefined },
  })
}

/* ──────────────────────────────────────────────────────── WordPress (plugin + key) */

const wordPressConnectResponseSchema = z.object({
  oauth_url: z.string().optional(),
  status: z.string().optional(),
  site_name: z.string().optional(),
  message: z.string().optional(),
})
export type WordPressConnectResult = z.infer<typeof wordPressConnectResponseSchema>

/**
 * POST wordpress/connect/ → connect a self-hosted WordPress site with the API key
 * generated by the Signalor GEO plugin. (For WordPress.com the backend returns an
 * `oauth_url` to redirect to instead.)
 */
export interface ConnectWordPressInput {
  email: string
  siteUrl: string
  apiKey: string
  returnTo?: string
}

export async function connectWordPress(
  input: ConnectWordPressInput,
): Promise<WordPressConnectResult> {
  const data = await apiPost<unknown>('/api/integrations/wordpress/connect/', {
    email: normalizeEmail(input.email),
    site_url: input.siteUrl,
    api_key: input.apiKey || undefined,
    return_to: input.returnTo || '/dashboard',
    frontend_base: frontendBase(),
  })
  return wordPressConnectResponseSchema.parse(data)
}

/** DELETE wordpress/disconnect/ → drop the WordPress connection for this account. */
export async function disconnectWordPress(email: string): Promise<void> {
  await apiDelete<unknown>('/api/integrations/wordpress/disconnect/', undefined, {
    params: { email: normalizeEmail(email) },
  })
}
